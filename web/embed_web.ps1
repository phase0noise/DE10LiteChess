$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$html = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'index.html'))
$css = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'style.css'))
$pieces = [Convert]::ToBase64String([IO.File]::ReadAllBytes((Join-Path $PSScriptRoot 'pieces.png')))
$css = $css.Replace("url('pieces.png')", "url('data:image/png;base64,$pieces')")
$html = $html.Replace('<link rel="stylesheet" href="style.css">', "<style>`n$css`n</style>")
foreach ($name in @('chess.js','fpga.js','app.js')) {
    $js = [IO.File]::ReadAllText((Join-Path $PSScriptRoot $name))
    $html = $html.Replace("<script src=`"$name`"></script>", "<script>`n$js`n</script>")
}
if ($html.Contains(')CHESS"')) { throw 'Page contains the C++ raw-string terminator.' }
$header = "#pragma once`n// Generated by web/embed_web.ps1; edit web/ sources.`nconst char WEB_PAGE[] = R`"CHESS($html)CHESS`";`n"
[IO.File]::WriteAllText((Join-Path $projectRoot 'firmware/pico_chess/web_page.h'),$header,[Text.UTF8Encoding]::new($false))
Write-Host "Embedded $($html.Length) characters, including the original chess artwork."
